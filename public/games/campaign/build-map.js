// One state path per postal code; adds a label point (centroid of the biggest ring), a bounding box, and the SVG's own border-pair list (used only by the dev mock).
const fs = require('fs');
const svg = fs.readFileSync(process.argv[2], 'utf8');
const NAMES = { al: 'Alabama', ak: 'Alaska', az: 'Arizona', ar: 'Arkansas', ca: 'California', co: 'Colorado', ct: 'Connecticut', de: 'Delaware', fl: 'Florida', ga: 'Georgia', hi: 'Hawaii', id: 'Idaho', il: 'Illinois', in: 'Indiana', ia: 'Iowa', ks: 'Kansas', ky: 'Kentucky', la: 'Louisiana', me: 'Maine', md: 'Maryland', ma: 'Massachusetts', mi: 'Michigan', mn: 'Minnesota', ms: 'Mississippi', mo: 'Missouri', mt: 'Montana', ne: 'Nebraska', nv: 'Nevada', nh: 'New Hampshire', nj: 'New Jersey', nm: 'New Mexico', ny: 'New York', nc: 'North Carolina', nd: 'North Dakota', oh: 'Ohio', ok: 'Oklahoma', or: 'Oregon', pa: 'Pennsylvania', ri: 'Rhode Island', sc: 'South Carolina', sd: 'South Dakota', tn: 'Tennessee', tx: 'Texas', ut: 'Utah', vt: 'Vermont', va: 'Virginia', wa: 'Washington', wv: 'West Virginia', wi: 'Wisconsin', wy: 'Wyoming' };

// path d -> list of rings (arrays of [x, y] endpoints); curves use their end point only (enough for a bbox / centroid)
function rings(d) {
  const t = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g); let i = 0, cmd = '', x = 0, y = 0, sx = 0, sy = 0, cur = null; const out = [];
  const num = () => parseFloat(t[i++]);
  const push = () => { if (cur) cur.push([x, y]); };
  while (i < t.length) {
    if (/[a-zA-Z]/.test(t[i])) cmd = t[i++];
    const rel = cmd === cmd.toLowerCase(), C = cmd.toUpperCase();
    if (C === 'Z') { x = sx; y = sy; if (cur && cur.length > 2) out.push(cur); cur = null; continue; }
    if (C === 'M') { const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; sx = x; sy = y; if (cur && cur.length > 2) out.push(cur); cur = [[x, y]]; cmd = rel ? 'l' : 'L'; continue; }
    if (C === 'L') { const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; }
    else if (C === 'H') { const a = num(); x = rel ? x + a : a; }
    else if (C === 'V') { const a = num(); y = rel ? y + a : a; }
    else if (C === 'C') { num(); num(); num(); num(); const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; }
    else if (C === 'S' || C === 'Q') { num(); num(); const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; }
    else if (C === 'T') { const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; }
    else if (C === 'A') { num(); num(); num(); num(); num(); const a = num(), b = num(); x = rel ? x + a : a; y = rel ? y + b : b; }
    else throw new Error('cmd ' + cmd);
    push();
  }
  if (cur && cur.length > 2) out.push(cur);
  return out;
}
const area = (r) => { let a = 0; for (let k = 0; k < r.length; k++) { const p = r[k], q = r[(k + 1) % r.length]; a += p[0] * q[1] - q[0] * p[1]; } return a / 2; };
const centroid = (r) => { const A = area(r); let cx = 0, cy = 0; for (let k = 0; k < r.length; k++) { const p = r[k], q = r[(k + 1) % r.length], f = p[0] * q[1] - q[0] * p[1]; cx += (p[0] + q[0]) * f; cy += (p[1] + q[1]) * f; } return [cx / (6 * A), cy / (6 * A)]; };
const r1 = (n) => Math.round(n * 10) / 10;

const states = {}, pairs = [];
for (const m of svg.matchAll(/<path\s+class="([a-z-]+)"\s+d="([^"]+)"/g)) {
  const cls = m[1], d = m[2];
  if (cls.includes('-')) { pairs.push(cls.toUpperCase()); continue; }
  if (!NAMES[cls]) continue;
  const rs = rings(d); const big = rs.reduce((a, b) => (Math.abs(area(b)) > Math.abs(area(a)) ? b : a));
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9; for (const r of rs) for (const p of r) { x0 = Math.min(x0, p[0]); y0 = Math.min(y0, p[1]); x1 = Math.max(x1, p[0]); y1 = Math.max(y1, p[1]); }
  states[cls.toUpperCase()] = { n: NAMES[cls], d: d.replace(/\s+/g, ' ').trim(), c: centroid(big).map(r1), b: [x0, y0, x1, y1].map(r1) };
}
if (Object.keys(states).length !== 50) throw new Error('states ' + Object.keys(states).length);
const [vw, vh] = [959, 593];
process.stdout.write('/* GENERATED by build-map.js from the CC0 Wikimedia "Blank US Map (states only)" SVG: see SOURCES.md. One path per state, keyed by postal code. */\n' +
  'window.CAMPAIGN_GEO = ' + JSON.stringify({ w: vw, h: vh, states, borders: pairs }) + ';\n');
